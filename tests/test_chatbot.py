# tests/test_chatbot.py
import unittest
import json
import os
from unittest.mock import patch, MagicMock

os.environ['SECRET_KEY'] = 'test-secret-key-123'

from app import app, db
import chatbot_service

class TestChatbot(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        app.config['TESTING'] = True
        cls.client = app.test_client()

    def test_01_required_question_skills_in_demand(self):
        """Test: What skills are most in demand?"""
        res = self.client.post('/api/chatbot', json={'message': 'What skills are most in demand?'})
        self.assertEqual(res.status_code, 200)
        data = json.loads(res.data)
        self.assertIn('response', data)
        resp = data['response']
        # Must not be the generic default fallback
        self.assertNotIn("I can help you with career information! You can ask me about:", resp)
        # Should mention key in-demand skill areas
        self.assertTrue(any(k in resp.lower() for k in ['ai', 'machine learning', 'cloud', 'backend', 'skills']))

