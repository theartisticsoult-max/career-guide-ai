    def test_06_conversation_context_passing(self):
        """Test that multi-turn history is accepted and integrated."""
        history = [
            {'role': 'user', 'content': 'Hi, I am interested in cloud computing.'},
            {'role': 'assistant', 'content': 'Cloud computing is a great choice! What would you like to know?'}
        ]
        res = self.client.post('/api/chatbot', json={
            'message': 'What certifications do you recommend for it?',
            'history': history
        })
        self.assertEqual(res.status_code, 200)
        data = json.loads(res.data)
        self.assertIn('response', data)
        self.assertTrue(len(data['response']) > 20)

    @patch('chatbot_service.get_groq_client')
    def test_07_groq_api_live_mock_integration(self, mock_client_factory):
        """Test that Groq API integration correctly parses completion response."""
        mock_client = MagicMock()
        mock_choice = MagicMock()
        mock_choice.message.content = "This is an intelligent AI response generated by Groq llama-3.3-70b-versatile."
        mock_completion = MagicMock()
        mock_completion.choices = [mock_choice]
        mock_client.chat.completions.create.return_value = mock_completion
        mock_client_factory.return_value = mock_client

        with patch.dict(os.environ, {'GROQ_API_KEY': 'gsk_mock_test_key_123', 'GROQ_MODEL': 'llama-3.3-70b-versatile'}):
            res = self.client.post('/api/chatbot', json={
                'message': 'How do I become a backend engineer?',
                'history': [{'role': 'user', 'content': 'Hello'}]
            })
            self.assertEqual(res.status_code, 200)
            data = json.loads(res.data)
            self.assertEqual(data['response'], "This is an intelligent AI response generated by Groq llama-3.3-70b-versatile.")
            
            # Verify client was called with correct model and parameters
            mock_client.chat.completions.create.assert_called_once()
            call_kwargs = mock_client.chat.completions.create.call_args[1]
            self.assertEqual(call_kwargs['model'], 'llama-3.3-70b-versatile')
            self.assertEqual(call_kwargs['temperature'], 0.7)
            # Verify system prompt and history included
            messages = call_kwargs['messages']
            self.assertEqual(messages[0]['role'], 'system')
            self.assertEqual(messages[1]['role'], 'user')
            self.assertEqual(messages[1]['content'], 'Hello')
            self.assertEqual(messages[2]['role'], 'user')
            self.assertEqual(messages[2]['content'], 'How do I become a backend engineer?')

    @patch('chatbot_service.get_groq_client')
    def test_08_groq_api_error_handling_and_fallback(self, mock_client_factory):
        """Test that Groq API errors are caught gracefully without failing the request."""
        mock_client = MagicMock()
        mock_client.chat.completions.create.side_effect = Exception("Groq rate limit exceeded (429)")
        mock_client_factory.return_value = mock_client

        with patch.dict(os.environ, {'GROQ_API_KEY': 'gsk_mock_test_key_123'}):
            res = self.client.post('/api/chatbot', json={
                'message': 'What skills are most in demand?'
            })
            self.assertEqual(res.status_code, 200)
            data = json.loads(res.data)
            # Must return fallback response, not a 500 error!
            self.assertIn('response', data)
            self.assertTrue(len(data['response']) > 50)
            self.assertIn('In-Demand Skills', data['response'])

    def test_09_empty_message_handling(self):
        """Test error handling on empty message."""
        res = self.client.post('/api/chatbot', json={'message': '   '})
        self.assertEqual(res.status_code, 400)
        data = json.loads(res.data)
        self.assertIn('response', data)

